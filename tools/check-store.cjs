const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const C=require('../catalog-utils.js');
const {answer}=require('../public-assistant.js');
const source=fs.readFileSync(path.join(root,'app.js'),'utf8');
const literal=source.match(/const PRODUCTS = (\[[\s\S]*?\n\]);/)[1];
const products=vm.runInNewContext('('+literal+')');
const p=id=>products.find(p=>p.id===id);
assert.equal(products.length,15);
assert.equal(C.mode(p('chatgpt')),'Cuenta compartida');
assert.equal(C.mode(p('capcut')),'Cuenta privada');
assert.equal(C.mode(p('canva')),'Modalidad por confirmar');
assert.equal(C.duration(p('duolingo')),'12 meses');
assert.equal(C.duration(p('chatgpt3')),'3 meses');
assert.equal(C.duration({...p('chatgpt'),days:45}),'45 días');
assert.equal(C.devices(p('claude')),'1 dispositivo');
assert.equal(C.devices(p('chatgpt3')),'Hasta 2 dispositivos');
assert.ok(C.matches(p('capcut'),'edicion'));
assert.equal(answer('Cuánto cuesta Chat GPT 3 meses',products).products[0].id,'chatgpt3');
assert.equal(answer('y por 6 meses',products,{family:'chatgpt'}).products[0].id,'chatgpt6');
assert.ok(answer('CapCut 6 meses',products).contact);
assert.ok(answer('CapCut hasta 10 mil',products).contact);
assert.ok(answer('Editar fotos',products).products.every(p=>p.cat==='Diseño'));
assert.equal(answer('Quiero comprar Canva',products).products[0].id,'canva');
assert.equal(answer('Premiere',products).products[0].id,'premiere');
assert.ok(answer('Mi ChatGPT no funciona',products).contact);
assert.ok(!answer('Mi ChatGPT no funciona',products).products);
assert.ok(answer('Como activo mi código',products).activate);
const budget=answer('Para editar videos hasta 15 mil',products).products;
assert.ok(budget.length>0&&budget.every(p=>p.price<=15000&&p.cat==='Edición de video'));
assert.ok(answer('qué clima hace',products).contact);
const updated=products.map(p=>({...p,price:77777}));
assert.equal(answer('Canva',updated).products[0].price,77777);
assert.equal(answer('Canva privada',products).text.includes('Modalidad por confirmar'),true);
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const shell=JSON.parse(sw.match(/const SHELL = (\[[^;]+\]);/)[1]);
for(const f of shell)assert.ok(fs.existsSync(path.join(root,f)),`Missing precache: ${f}`);
for(const f of ['app.js','assistants.js','public-assistant.js','store-tools.js','catalog-utils.js','sw.js'])execFileSync(process.execPath,['--check',path.join(root,f)]);
console.log('PASS: 15 planes; modalidad, dispositivos, duracion, busqueda, contexto, presupuesto, precios actualizados, recursos offline y sintaxis.');
